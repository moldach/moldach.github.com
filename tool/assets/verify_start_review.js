// Run with playwright-cli run-code --filename tool/assets/verify_start_review.js.
// This uses isolated browser contexts; no physical-device claim is made.
async (page) => {
  const url = 'http://127.0.0.1:4322/review/start/';
  const results = {};
  const errors = [];
  page.on('pageerror', error => errors.push(String(error)));
  const ready = p => p.waitForFunction(() => document.querySelector('main')?.dataset.state === 'ready', null, {timeout:45000});
  const metrics = p => p.locator('[data-metrics]').textContent().then(JSON.parse);
  const assert = (condition, message) => { if (!condition) throw new Error(message); };
  await page.setViewportSize({width:1600,height:1280});
  await page.goto(url);
  await ready(page);
  console.log('CHECK desktop ready');
  const initial = await metrics(page);
  assert(initial.shadowUpdateDrawCalls<=150,'Shadow-update rendering exceeds 150 draw calls');
  assert(initial.asset==='ktx2' && initial.approvedImages.length===10 && initial.chapters.length===6,'Main asset or metadata failed');
  assert(await page.locator('meta[name=robots]').getAttribute('content') === 'noindex, nofollow','Review must be noindexed');
  await page.screenshot({path:'output/playwright/start-webgl-studio.png',fullPage:true});
  const reference = await page.locator('canvas').screenshot({path:'output/playwright/start-webgl-reference-camera.png'});
  await page.locator('canvas').focus();
  await page.keyboard.press('ArrowLeft');
  const rotated = await page.locator('canvas').screenshot();
  assert(!reference.equals(rotated),'Keyboard inspection did not change view');
  await page.keyboard.press('Escape');
  await page.locator('canvas').screenshot();
  const resetPose=(await metrics(page)).camera;
  assert(resetPose.position.every((v,i)=>Math.abs(v-initial.camera.position[i])<1e-6) && resetPose.target.every((v,i)=>Math.abs(v-initial.camera.target[i])<1e-6),'Escape did not restore reference camera');
  for (const preset of ['neutral','contrast','studio']) {
    await page.locator(`input[value=${preset}]`).check();
    assert((await metrics(page)).lighting===preset,'Lighting control did not update');
    if(preset==='contrast') await page.screenshot({path:'output/playwright/start-webgl-contrast.png',fullPage:true});
  }
  const studio = await page.locator('canvas').screenshot();
  await page.locator('input[type=range]').fill('1.8');
  const brighter=await page.locator('canvas').screenshot();
  assert(!studio.equals(brighter),'Exposure did not change rendering');
  await page.locator('input[type=range]').fill('1.5');
  await page.locator('[data-measure]').click();
  await page.waitForFunction(()=>JSON.parse(document.querySelector('[data-metrics]').textContent).frameTiming?.frames===120,null,{timeout:30000});
  results.desktop=await metrics(page);
  console.log('CHECK desktop controls and timing passed');
  const browser=page.context().browser();
  assert(browser,'Browser unavailable for isolated test contexts');
  const mobileContext=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:2,isMobile:true,hasTouch:true,reducedMotion:'reduce'});
  const mobile=await mobileContext.newPage();
  await mobile.goto(url);await ready(mobile);
  await mobile.locator('canvas').scrollIntoViewIfNeeded();
  const bounds=await mobile.locator('canvas').boundingBox();
  const beforeTouch=await mobile.locator('canvas').screenshot();
  const cdp=await mobileContext.newCDPSession(mobile);
  const x=bounds.x+bounds.width/2,y=bounds.y+bounds.height/2;
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:x+30,y:y+5}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  const afterTouch=await mobile.locator('canvas').screenshot();
  assert(!beforeTouch.equals(afterTouch),'Touch inspection did not change view');
  await mobile.locator('[data-reset]').click();
  await mobile.locator('[data-measure]').click();
  await mobile.waitForFunction(()=>JSON.parse(document.querySelector('[data-metrics]').textContent).frameTiming?.frames===120,null,{timeout:30000});
  console.log('CHECK mobile touch and timing passed');
  results.mobileEmulation=await metrics(mobile);
  await mobile.screenshot({path:'output/playwright/start-webgl-mobile.png',fullPage:true});
  await mobileContext.close();
  const fallbackContext=await browser.newContext();
  const fallback=await fallbackContext.newPage();
  await fallback.route('**/models/start/start.glb',route=>route.abort('failed'));
  await fallback.goto(url);await ready(fallback);
  results.automaticFallback=await metrics(fallback);
  assert(results.automaticFallback.asset==='conventional','Compression/network fallback failed');
  await fallback.locator('[data-close]').click();
  results.disposal=await metrics(fallback);
  assert(results.disposal.resourcesDisposed && results.disposal.contextReleased && results.disposal.state==='closed','Close did not dispose resources');
  assert(await fallback.locator('[data-poster]').isVisible(),'Close did not restore poster');
  await fallbackContext.close();
  const unavailableContext=await browser.newContext();
  const unavailable=await unavailableContext.newPage();
  await unavailable.route('**/models/start/*.glb',route=>route.abort('failed'));
  await unavailable.goto(url);
  await unavailable.waitForFunction(()=>document.querySelector('main')?.dataset.state==='error');
  assert(await unavailable.locator('[data-poster]').isVisible(),'Load failure did not show poster');
  results.bothAssetsUnavailable={posterVisible:true,state:(await metrics(unavailable)).state};
  await unavailableContext.close();
  const noGLContext=await browser.newContext();
  await noGLContext.addInitScript(()=>{const original=HTMLCanvasElement.prototype.getContext;HTMLCanvasElement.prototype.getContext=function(type,...args){if(String(type).includes('webgl'))return null;return original.call(this,type,...args);};});
  const noGL=await noGLContext.newPage();await noGL.goto(url);
  await noGL.waitForFunction(()=>document.querySelector('main')?.dataset.state==='error');
  assert(await noGL.locator('[data-poster]').isVisible(),'No-WebGL poster failed');
  results.noWebGL={posterVisible:true};await noGLContext.close();
  const noJSContext=await browser.newContext({javaScriptEnabled:false});
  const noJS=await noJSContext.newPage();await noJS.goto(url);
  assert(await noJS.locator('[data-poster]').isVisible(),'No-JS poster failed');
  results.noJavaScript={posterVisible:true,articleHref:await noJS.getByRole('link',{name:'Read the style-transfer article'}).getAttribute('href')};await noJSContext.close();
  await page.locator('canvas').evaluate(canvas=>canvas.getContext('webgl2').getExtension('WEBGL_lose_context').loseContext());
  await page.waitForFunction(()=>document.querySelector('main')?.dataset.state==='context-lost');
  assert(await page.locator('[data-poster]').isVisible(),'Context loss poster failed');
  results.contextLoss={posterVisible:true};
  assert(errors.length===0,errors.join('\n'));
  results.desktopPageErrors=errors;
  return results;
}
